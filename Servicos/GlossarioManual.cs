    // Palavra portuguesa (sem acento, maiúscula) → palavras inglesas.
    public static readonly Dictionary<string, string[]> Ingles = Lista
        .Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
        .Select(l => l.Split('='))
        .Where(p => p.Length == 2)
        .GroupBy(p => p[0])
        .ToDictionary(g => g.Key, g => g.SelectMany(p => p[1].Split(',', StringSplitOptions.TrimEntries)).Distinct().ToArray());

    // As inglesas de uma palavra da tarefa (aceita o plural: SENSORES, CONFIGURACOES, UNIDADES).
    public static IEnumerable<string> Traducoes(string palavraSemAcento)
    {
        var p = palavraSemAcento;
        var formas = new List<string> { p };
        if (p.EndsWith("OES")) formas.Add(p[..^3] + "AO");
        if (p.EndsWith("ES")) formas.Add(p[..^2]);
        if (p.EndsWith('S')) formas.Add(p[..^1]);
        foreach (var f in formas)
            if (Ingles.TryGetValue(f, out var en)) return en;
        return [];
    }
